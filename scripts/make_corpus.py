"""Generate the benchmark's fault corpus as YAML files in benchmark/cases/ (LH-068, D-76).

Run `uv run python scripts/make_corpus.py` to rewrite the files. The output depends only on this
file, the NSE calendar seed and the fixed constants below, so regenerating gives identical files
and a change to the corpus is a reviewable diff of both this script and the YAML.

The matrix is 2 feeds x 5 fault classes x 10 cases = 100. For every feed and class, 3 cases are
the seed split (retrieval may learn from them) and 7 are the test split (the only ones scored,
FR-BEN-07). Dates are spread over the range with a hash of the case id, never chosen by hand, and
only dates on which the feed is expected to publish are used.
"""

from __future__ import annotations

import hashlib
from collections.abc import Callable
from datetime import date, timedelta
from pathlib import Path
from typing import Any

import yaml

from lineageheal.ingestion.calendar import DEFAULT_SEED, expectation, read_seed

OUT = Path(__file__).resolve().parents[1] / "benchmark" / "cases"
FIRST_DATE = date(2024, 1, 2)  # UDiFF bhavcopy is served from here (D-20)
LAST_DATE = date(2026, 10, 23)
# The held-out July 2024 replay (LH-071) owns this window; no corpus case may touch it.
RESERVED = (date(2024, 7, 1), date(2024, 7, 15))
PER_CLASS = 10
SEED_PER_CLASS = 3

HEADER = "# Generated by scripts/make_corpus.py (LH-068). Edit the script, not this file.\n"

Variant = dict[str, Any]


def _amfi_variants() -> dict[str, list[Variant]]:
    nav = "Net Asset Value"
    return {
        "schema_drift": [
            {"column": nav, "new_name": "NAV"},
            {"column": nav, "new_name": "Net Asset Value (Rs.)"},
            {"column": "Date", "new_name": "NAV Date"},
            {"column": "Scheme Code", "new_name": "Code"},
            {"column": "Scheme Code", "new_name": "SchemeCode"},
        ],
        "nulls": [
            {"column": nav},
            {"column": "Date"},
            {"column": "Scheme Code"},
            {"column": "NAV Name"},
            {"column": "ISIN Div Payout/ISIN Growth"},
        ],
        "unit_change": [
            {"column": nav, "factor": 100},
            {"column": nav, "factor": 1000},
            {"column": nav, "factor": 10},
            {"column": nav, "factor": 100},
            {"column": nav, "factor": 10000},
        ],
        "late_data": [{"column": "Date"}],
        "duplicates": [{}],
    }


def _nse_variants() -> dict[str, list[Variant]]:
    return {
        "schema_drift": [
            {"column": "ClsPric", "new_name": "ClosePrice"},
            {"column": "OpnPric", "new_name": "OpenPrice"},
            {"column": "TtlTradgVol", "new_name": "Volume"},
            {"column": "TckrSymb", "new_name": "Symbol"},
            {"column": "ISIN", "new_name": "IsinCode"},
        ],
        "nulls": [
            {"column": "ClsPric"},
            {"column": "OpnPric"},
            {"column": "TtlTradgVol"},
            {"column": "TckrSymb"},
            {"column": "ISIN"},
        ],
        "unit_change": [
            {"column": "ClsPric", "factor": 100},
            {"column": "OpnPric", "factor": 100},
            {"column": "HghPric", "factor": 1000},
            {"column": "LwPric", "factor": 100},
            {"column": "ClsPric", "factor": 10},
        ],
        "late_data": [{"column": "TradDt"}],
        "duplicates": [{}],
    }


def _amfi_stale(day: date) -> str:
    return (day - timedelta(days=7)).strftime("%d-%b-%Y")


def _nse_stale(day: date) -> str:
    return (day - timedelta(days=7)).isoformat()


FEEDS: dict[str, dict[str, Any]] = {
    "amfi": {
        "dataset": "navall",
        "variants": _amfi_variants(),
        "stale": _amfi_stale,
        "nse_calendar": False,
    },
    "nse": {
        "dataset": "cm_bhavcopy",
        "variants": _nse_variants(),
        "stale": _nse_stale,
        "nse_calendar": True,
    },
}
SLUG = {
    "schema_drift": "schema-drift",
    "nulls": "nulls",
    "duplicates": "duplicates",
    "unit_change": "unit-change",
    "late_data": "late-data",
}


def _hash(text: str) -> int:
    return int(hashlib.sha256(text.encode()).hexdigest(), 16)


def pick_dates(source: str, count: int) -> list[date]:
    """Distinct dates for a feed, spread evenly over the range, nudged by a hash of the slot.

    The range is cut into `count` equal windows and one eligible date is taken from each, so the
    dates cover the whole period instead of clustering.
    """
    entries = read_seed(DEFAULT_SEED)
    pool: list[date] = []
    day = FIRST_DATE
    while day <= LAST_DATE:
        reserved = RESERVED[0] <= day <= RESERVED[1]
        if not reserved and expectation(source, day, entries)[1]:
            pool.append(day)
        day += timedelta(days=1)
    window = len(pool) // count
    return [pool[i * window + _hash(f"{source}:{i}") % window] for i in range(count)]


def build() -> dict[str, dict[str, Any]]:
    """Every case, keyed by id."""
    cases: dict[str, dict[str, Any]] = {}
    for source, feed in FEEDS.items():
        dataset = feed["dataset"]
        stale: Callable[[date], str] = feed["stale"]
        # One date per case, assigned so that no class gets only one end of the range.
        dates = pick_dates(source, PER_CLASS * len(SLUG))
        # Interleave: slot k of class c uses date index k * classes + c.
        for c, (fault_class, slug) in enumerate(SLUG.items()):
            variants = feed["variants"][fault_class]
            for k in range(PER_CLASS):
                number = k + 1
                case_id = f"{source}-{slug}-{number:03d}"
                day = dates[k * len(SLUG) + c]
                variant = variants[k % len(variants)]
                split = "seed" if k < SEED_PER_CLASS else "test"
                root = f"raw.{source}.{dataset}.{variant.get('column', '*')}"
                fix = "dbt"
                if fault_class == "schema_drift":
                    injection = {"type": "rename_column", **variant}
                elif fault_class == "nulls":
                    injection = {"type": "blank_value", **variant}
                elif fault_class == "unit_change":
                    injection = {"type": "scale_values", **variant}
                elif fault_class == "duplicates":
                    injection = {"type": "duplicate_row"}
                    root = f"raw.{source}.{dataset}.*"
                elif k % 2 == 0:
                    # Late data: half the cases never arrive, half arrive with an old date.
                    injection = {"type": "withhold_file"}
                    root = f"raw.{source}.{dataset}.*"
                    fix = "outside_dbt"
                else:
                    injection = {"type": "stale_date", **variant, "value": stale(day)}
                    fix = "outside_dbt"
                cases[case_id] = {
                    "id": case_id,
                    "class": fault_class,
                    "source": source,
                    "dataset": dataset,
                    "trade_date": day,
                    "split": split,
                    "seed": _hash(case_id) % 1000,
                    "injection": injection,
                    "expected": {"root_cause": root, "fix_location": fix},
                }
    return cases


def main() -> None:
    """Rewrite benchmark/cases/ so it holds exactly the generated cases."""
    OUT.mkdir(parents=True, exist_ok=True)
    cases = build()
    for stale_file in OUT.glob("*.yaml"):
        if stale_file.stem not in cases:
            stale_file.unlink()
    for case_id, case in cases.items():
        text = yaml.safe_dump(case, sort_keys=False, allow_unicode=True)
        (OUT / f"{case_id}.yaml").write_text(HEADER + text, encoding="utf-8")


if __name__ == "__main__":
    main()
